/**
 * คู่มือการใช้งาน — the one screen in this app that is the same for everybody.
 *
 * ── WHY IT IS NOT A TAB ────────────────────────────────────────────────────
 *
 * Every other screen here is a `tabs.push` in `Shell`, and a push carries two
 * partitions with it: `group` for the sidebar's three blocks and `bar` for the
 * phone's slots. The phone bar is capped at four columns — `test/roleNavTabs`
 * asserts it per บทบาท — and a ผู้เซ็น already fills all four with one screen
 * apiece. A twelfth tab for everybody would have made that bar five wide, or
 * put a sheet on a slot that is currently one press to one screen, and it would
 * have done it to buy a page nobody opens twice a week.
 *
 * So it is reached the way ข้อมูลส่วนตัว is: a row in the sidebar's foot and a
 * row in the phone drawer, neither of them gated on บทบาท. `PAGE.manual` gives
 * it its heading exactly as every tab has one, and `Shell` draws it beside the
 * rest — from the shell's point of view it is a screen like any other; it is
 * only the MENU that is arranged differently.
 *
 * ── WHY THE SCREEN IS ITSELF A MENU ────────────────────────────────────────
 *
 * Eleven topics as one scrolling page is a page that gets scrolled past. The
 * index is the screen, and a topic opens over it — so the way in is a list of
 * questions somebody actually has, and the answer arrives on its own.
 *
 * `useBackHandler` puts an open topic on the shell's back stack, so the
 * appbar's ‹ and a phone's back gesture close the topic before they leave the
 * screen. Same registration the OT form and the printable sheet make.
 *
 * ── WHAT IT MAY SAY, AND WHAT IT MUST NOT ──────────────────────────────────
 *
 * IT DESCRIBES MECHANISM, NEVER A POLICY FIGURE. เพดาน, การปัดเศษ, เวลางาน
 * ปกติ, จำนวนวันที่ยื่นล่วงหน้าได้ — every one of those is a value ฝ่ายบุคคล can
 * change on ตั้งค่าระบบ without anybody touching this file, and a manual that
 * printed today's number would be wrong the first time they did. It says WHERE
 * the number is instead, which stays true.
 *
 * That is not a style preference: docs/hr-briefing.md carries a table of those
 * same values, read off the machine on a stated date and marked with the date
 * for exactly this reason. A copy of it in the app with no date on it would be
 * the version people believe.
 */

